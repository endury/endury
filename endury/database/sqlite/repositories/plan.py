"""Repository for training plans and sessions.

Persists plans generated by the planner session-menu engine and their
individual workout sessions. Supports at most one active plan at a time.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from typing import Any

from endury.common import clock
from endury.database.sqlite.repositories.write_models import SessionInsertRow
from endury.database.sqlite.session import DatabaseSession

logger = logging.getLogger(__name__)


@dataclass
class MacroPlanRow:
    """Database row for macro_plans table."""

    id: int
    goal_type: str
    goal_date: str
    plan_start: str
    total_weeks: int
    ambition_level: str
    weeks_json: str
    coaching_brief: str
    revision: int
    revision_reason: str | None
    status: str
    created_at: str
    updated_at: str


@dataclass
class PlanRow:
    """Lightweight projection of a persisted plan."""

    id: int
    name: str
    goal_type: str
    goal_date: str
    plan_start: str
    athlete_state_json: str | None
    solve_result_json: str
    solver_version: str
    input_hash: str
    macro_plan_id: int | None
    revision: int
    status: str
    created_at: str
    updated_at: str


@dataclass
class PlanSessionRow:
    """Lightweight projection of a persisted plan session."""

    id: int
    plan_id: int
    slot_id: str
    date: str
    week_index: int
    phase_type: str
    sport: str
    activity_key: str
    family: str
    target_tss: float
    achieved_tss: float
    duration_minutes: float | None
    workout_json: str
    matched_activity_id: int | str | None
    status: str
    duration_target_minutes: float | None = None
    tid_fractions_json: str | None = None
    pushed_event_json: str | None = None
    optional: bool = False


class PlanRepository:
    """CRUD operations for plans and plan sessions."""

    def __init__(self, session: DatabaseSession) -> None:
        self._session = session

    # -- Plan CRUD ----------------------------------------------------------

    def get_active(self) -> PlanRow | None:
        """Get the currently active plan.

        Returns:
            PlanRow or None if no active plan exists.
        """
        with self._session.cursor() as cursor:
            cursor.execute("SELECT * FROM plans WHERE status = 'active' LIMIT 1")
            row = cursor.fetchone()
            if row is None:
                return None
            return _plan_from_row(row)

    def get_by_id(self, plan_id: int) -> PlanRow | None:
        """Get a plan by its ID.

        Args:
            plan_id: The plan ID.
        """
        with self._session.cursor() as cursor:
            cursor.execute("SELECT * FROM plans WHERE id = ?", (plan_id,))
            row = cursor.fetchone()
            if row is None:
                return None
            return _plan_from_row(row)

    def create(
        self,
        *,
        name: str,
        goal_type: str,
        goal_date: str,
        plan_start: str,
        solve_result_json: str,
        solver_version: str,
        input_hash: str,
        athlete_state_json: str | None = None,
        macro_plan_id: int | None = None,
    ) -> int:
        """Create a new plan, archiving any existing active plan.

        Args:
            name: Human-readable plan name.
            goal_type: Goal type (e.g. 'running_marathon').
            goal_date: ISO date of the goal race.
            plan_start: ISO date of plan start.
            solve_result_json: Serialized PlanResult.
            solver_version: Engine version string.
            input_hash: SHA-256 of canonical input.
            athlete_state_json: Serialized AthleteState snapshot.
            macro_plan_id: Optional id linking this plan to a macro plan.

        Returns:
            The new plan ID.
        """
        now = clock.now().isoformat()
        with self._session.cursor() as cursor:
            # Archive any existing active plan
            cursor.execute(
                "UPDATE plans SET status = 'archived', updated_at = ? "
                "WHERE status = 'active'",
                (now,),
            )
            cursor.execute(
                """
                INSERT INTO plans (
                    name, goal_type, goal_date, plan_start,
                    athlete_state_json, solve_result_json,
                    solver_version, input_hash,
                    macro_plan_id, revision, status,
                    created_at, updated_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 1, 'active', ?, ?)
                """,
                (
                    name,
                    goal_type,
                    goal_date,
                    plan_start,
                    athlete_state_json,
                    solve_result_json,
                    solver_version,
                    input_hash,
                    macro_plan_id,
                    now,
                    now,
                ),
            )
            plan_id = cursor.lastrowid
        logger.info("Created plan %d: %s (%s)", plan_id, name, goal_type)
        return plan_id  # type: ignore[return-value]

    def archive(self, plan_id: int) -> None:
        """Archive a plan by setting status to 'archived'.

        Args:
            plan_id: The plan ID to archive.
        """
        now = clock.now().isoformat()
        with self._session.cursor() as cursor:
            cursor.execute(
                "UPDATE plans SET status = 'archived', updated_at = ? WHERE id = ?",
                (now, plan_id),
            )

    # -- Macro Plan CRUD ----------------------------------------------------

    def get_active_macro(self) -> MacroPlanRow | None:
        """Get the currently active macro plan.

        Returns:
            MacroPlanRow or None if no active macro plan exists.
        """
        with self._session.cursor() as cursor:
            cursor.execute(
                "SELECT * FROM macro_plans WHERE status = 'active' "
                "ORDER BY id DESC LIMIT 1"
            )
            row = cursor.fetchone()
            if row is None:
                return None
            return _macro_plan_from_row(row)

    def get_macro_by_id(self, macro_id: int) -> MacroPlanRow | None:
        """Get macro plan by id."""
        with self._session.cursor() as cursor:
            cursor.execute("SELECT * FROM macro_plans WHERE id = ?", (macro_id,))
            row = cursor.fetchone()
            if row is None:
                return None
            return _macro_plan_from_row(row)

    def get_macro_for_plan(self, plan: PlanRow) -> MacroPlanRow | None:
        """Get macro plan linked to a plan row, falling back to active macro."""
        if plan.macro_plan_id is not None:
            macro = self.get_macro_by_id(plan.macro_plan_id)
            if macro is not None:
                return macro
        return self.get_active_macro()

    def create_macro(
        self,
        *,
        goal_type: str,
        goal_date: str,
        plan_start: str,
        total_weeks: int,
        ambition_level: str,
        weeks_json: str,
        coaching_brief: str,
        revision: int = 1,
        revision_reason: str | None = None,
    ) -> int:
        """Create a new macro plan, archiving any existing active one.

        Args:
            goal_type: Goal type string (e.g. 'running_marathon').
            goal_date: ISO date of the goal race.
            plan_start: ISO date of plan start.
            total_weeks: Total number of weeks in the plan.
            ambition_level: Ambition level string.
            weeks_json: JSON-encoded list of macro week dicts.
            coaching_brief: The deterministic templated plan narrative (see
                ``coach_brief.build_coach_brief``).
            revision: Revision number (default 1).
            revision_reason: Optional reason for this revision.

        Returns:
            The new macro plan ID.
        """
        now = clock.now().isoformat()
        with self._session.cursor() as cursor:
            # Archive any existing active macro plan
            cursor.execute(
                "UPDATE macro_plans SET status = 'archived', updated_at = ? "
                "WHERE status = 'active'",
                (now,),
            )
            cursor.execute(
                """
                INSERT INTO macro_plans (
                    goal_type, goal_date, plan_start, total_weeks,
                    ambition_level, weeks_json, coaching_brief,
                    revision, revision_reason, status, created_at, updated_at
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 'active', ?, ?)
                """,
                (
                    goal_type,
                    goal_date,
                    plan_start,
                    total_weeks,
                    ambition_level,
                    weeks_json,
                    coaching_brief,
                    revision,
                    revision_reason,
                    now,
                    now,
                ),
            )
            macro_id = cursor.lastrowid
        logger.info("Created macro plan %d: %s (%s)", macro_id, goal_type, goal_date)
        return macro_id  # type: ignore[return-value]

    def revise_macro(
        self,
        macro_id: int,
        *,
        weeks_json: str,
        coaching_brief: str,
        revision: int,
        revision_reason: str | None,
    ) -> None:
        """Update macro plan with revised content.

        Args:
            macro_id: The macro plan ID to revise.
            weeks_json: Updated JSON-encoded weeks.
            coaching_brief: Updated coaching brief.
            revision: New revision number.
            revision_reason: Reason for revision.
        """
        now = clock.now().isoformat()
        with self._session.cursor() as cursor:
            cursor.execute(
                "UPDATE macro_plans SET weeks_json = ?, coaching_brief = ?, "
                "revision = ?, revision_reason = ?, updated_at = ? WHERE id = ?",
                (weeks_json, coaching_brief, revision, revision_reason, now, macro_id),
            )

    def archive_macro(self, macro_id: int) -> None:
        """Archive a macro plan.

        Args:
            macro_id: The macro plan ID to archive.
        """
        now = clock.now().isoformat()
        with self._session.cursor() as cursor:
            cursor.execute(
                "UPDATE macro_plans SET status = 'archived', updated_at = ? "
                "WHERE id = ?",
                (now, macro_id),
            )

    def update_solve_result_json(self, plan_id: int, solve_result_json: str) -> None:
        """Update persisted solve payload for a plan."""
        now = clock.now().isoformat()
        with self._session.cursor() as cursor:
            cursor.execute(
                "UPDATE plans SET solve_result_json = ?, updated_at = ? WHERE id = ?",
                (solve_result_json, now, plan_id),
            )

    def delete_future_sessions(self, plan_id: int, from_date: str) -> int:
        """Delete unmatched future sessions from a plan for replan.

        Args:
            plan_id: The plan ID.
            from_date: ISO date from which to delete (inclusive).

        Returns:
            Number of sessions deleted.
        """
        with self._session.cursor() as cursor:
            cursor.execute(
                "DELETE FROM plan_sessions "
                "WHERE plan_id = ? AND date >= ? AND matched_activity_id IS NULL",
                (plan_id, from_date),
            )
            deleted = cursor.rowcount
        logger.info(
            "Deleted %d future sessions from plan %d from %s",
            deleted,
            plan_id,
            from_date,
        )
        return deleted

    # -- Session CRUD -------------------------------------------------------

    def get_sessions(self, plan_id: int) -> list[PlanSessionRow]:
        """Get all sessions for a plan, ordered by date.

        Args:
            plan_id: The plan ID.
        """
        with self._session.cursor() as cursor:
            cursor.execute(
                "SELECT * FROM plan_sessions WHERE plan_id = ? ORDER BY date, slot_id",
                (plan_id,),
            )
            return [_session_from_row(row) for row in cursor.fetchall()]

    def get_session_by_id(self, session_id: int) -> PlanSessionRow | None:
        """Get one plan session by its row id.

        Args:
            session_id: The ``plan_sessions`` row id.

        Returns:
            The session, or None when no row has that id.
        """
        with self._session.cursor() as cursor:
            cursor.execute("SELECT * FROM plan_sessions WHERE id = ?", (session_id,))
            row = cursor.fetchone()
        return _session_from_row(row) if row is not None else None

    def get_sessions_by_date_range(
        self, plan_id: int, start_date: str, end_date: str
    ) -> list[PlanSessionRow]:
        """Get sessions for a plan within a date range.

        Args:
            plan_id: The plan ID.
            start_date: ISO date (inclusive).
            end_date: ISO date (inclusive).
        """
        with self._session.cursor() as cursor:
            cursor.execute(
                "SELECT * FROM plan_sessions "
                "WHERE plan_id = ? AND date >= ? AND date <= ? "
                "ORDER BY date, slot_id",
                (plan_id, start_date, end_date),
            )
            return [_session_from_row(row) for row in cursor.fetchall()]

    def bulk_insert_sessions(
        self,
        plan_id: int,
        sessions: list[SessionInsertRow],
    ) -> int:
        """Insert multiple sessions for a plan.

        Args:
            plan_id: The plan ID.
            sessions: Typed SessionInsertRow objects.

        Returns:
            Number of sessions inserted.
        """
        rows = [s.to_dict() for s in sessions]
        with self._session.cursor() as cursor:
            cursor.executemany(
                """
                INSERT INTO plan_sessions (
                    plan_id, slot_id, date, week_index, phase_type,
                    sport, activity_key, family, target_tss, achieved_tss,
                    duration_minutes, workout_json,
                    duration_target_minutes, tid_fractions_json, optional,
                    status
                ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'pending')
                """,
                [
                    (
                        plan_id,
                        s["slot_id"],
                        s["date"],
                        s["week_index"],
                        s["phase_type"],
                        s["sport"],
                        s["activity_key"],
                        s["family"],
                        s["target_tss"],
                        s["achieved_tss"],
                        s.get("duration_minutes"),
                        s["workout_json"],
                        s.get("duration_target_minutes"),
                        s.get("tid_fractions_json"),
                        int(s.get("optional", False)),
                    )
                    for s in rows
                ],
            )
        logger.info("Inserted %d sessions for plan %d", len(rows), plan_id)
        return len(rows)

    def update_session_status(
        self,
        session_id: int,
        status: str,
        matched_activity_id: int | str | None = None,
    ) -> None:
        """Update a session's status and optional activity match.

        Args:
            session_id: The session ID.
            status: New status ('pending', 'completed', 'skipped', 'unlinked').
            matched_activity_id: Optional ID of the matched activity.
        """
        with self._session.cursor() as cursor:
            cursor.execute(
                "UPDATE plan_sessions SET status = ?, matched_activity_id = ? "
                "WHERE id = ?",
                (status, matched_activity_id, session_id),
            )

    def update_session_date(
        self,
        session_id: int,
        plan_id: int,
        new_date: str,
        *,
        week_index: int,
        phase_type: str | None = None,
    ) -> bool:
        """Move a session to another date within its plan.

        Args:
            session_id: The session ID.
            plan_id: The plan the session must belong to.
            new_date: New ISO date for the session.
            week_index: The plan week the new date falls in — kept in step
                with the date so week-grouped views don't misfile the row.
            phase_type: The target week's phase, so a cross-phase move stops
                reporting the phase it left; ``None`` keeps the stored one
                (the caller could not determine the target week's phase).

        Returns:
            True when a row was updated, False when no matching session exists.
        """
        with self._session.cursor() as cursor:
            cursor.execute(
                "UPDATE plan_sessions SET date = ?, week_index = ?, "
                "phase_type = COALESCE(?, phase_type) "
                "WHERE id = ? AND plan_id = ?",
                (new_date, week_index, phase_type, session_id, plan_id),
            )
            return cursor.rowcount > 0

    def update_session_prescription(
        self,
        session_id: int,
        plan_id: int,
        *,
        target_tss: float,
        achieved_tss: float,
        duration_minutes: float,
        workout_json: str,
        tid_fractions_json: str | None,
    ) -> bool:
        """Rewrite one session's prescription within its plan.

        ``duration_target_minutes`` is deliberately NOT written: it is the
        planner's original hours-space intent and therefore the immutable
        base every week adjustment scales from and that a 0% adjustment
        restores to. Date, week_index, status and matched_activity_id are
        untouched.

        Args:
            session_id: The session ID.
            plan_id: The plan the session must belong to.
            target_tss: New planned TSS.
            achieved_tss: New post-quantization TSS.
            duration_minutes: New materialized duration in minutes.
            workout_json: New serialized workout (steps + coaching_intent).
            tid_fractions_json: New serialized TID fractions, or None.

        Returns:
            True when a row was updated, False when no matching session exists.
        """
        with self._session.cursor() as cursor:
            cursor.execute(
                "UPDATE plan_sessions SET target_tss = ?, achieved_tss = ?, "
                "duration_minutes = ?, workout_json = ?, tid_fractions_json = ? "
                "WHERE id = ? AND plan_id = ?",
                (
                    target_tss,
                    achieved_tss,
                    duration_minutes,
                    workout_json,
                    tid_fractions_json,
                    session_id,
                    plan_id,
                ),
            )
            return cursor.rowcount > 0

    def update_session_swap(
        self,
        session_id: int,
        plan_id: int,
        *,
        sport: str,
        activity_key: str,
        family: str,
        target_tss: float,
        achieved_tss: float,
        duration_minutes: float | None,
        duration_target_minutes: float | None,
        workout_json: str,
        tid_fractions_json: str | None,
    ) -> bool:
        """Replace one session's workout identity and prescription in place.

        Wider than :meth:`update_session_prescription`: a swap changes what
        the session *is* (sport, activity, family), so it also rewrites
        ``duration_target_minutes`` — the retired activity's hours-space
        intent is meaningless once the workout is gone, and a later week
        adjustment must scale from the swapped-in duration. Date,
        week_index, slot_id, status and matched_activity_id are untouched.

        Args:
            session_id: The session ID.
            plan_id: The plan the session must belong to.
            sport: New sport value string.
            activity_key: New activity key.
            family: New activity family.
            target_tss: New planned TSS.
            achieved_tss: New post-quantization TSS.
            duration_minutes: New materialized duration in minutes.
            duration_target_minutes: New hours-space duration base.
            workout_json: New serialized workout (steps + coaching_intent).
            tid_fractions_json: New serialized TID fractions, or None.

        Returns:
            True when a row was updated, False when no matching session exists.
        """
        with self._session.cursor() as cursor:
            cursor.execute(
                "UPDATE plan_sessions SET sport = ?, activity_key = ?, family = ?, "
                "target_tss = ?, achieved_tss = ?, duration_minutes = ?, "
                "duration_target_minutes = ?, workout_json = ?, "
                "tid_fractions_json = ? WHERE id = ? AND plan_id = ?",
                (
                    sport,
                    activity_key,
                    family,
                    target_tss,
                    achieved_tss,
                    duration_minutes,
                    duration_target_minutes,
                    workout_json,
                    tid_fractions_json,
                    session_id,
                    plan_id,
                ),
            )
            return cursor.rowcount > 0

    def update_pushed_events(
        self,
        plan_id: int,
        pushed_by_slot: dict[str, str],
    ) -> int:
        """Record the calendar event last pushed for each session.

        Args:
            plan_id: The plan the sessions belong to.
            pushed_by_slot: ``slot_id`` -> JSON of the event we pushed, as
                sent to intervals.icu. Slots with no row are ignored.

        Returns:
            Number of session rows updated.
        """
        if not pushed_by_slot:
            return 0

        with self._session.cursor() as cursor:
            cursor.executemany(
                "UPDATE plan_sessions SET pushed_event_json = ? "
                "WHERE plan_id = ? AND slot_id = ?",
                [
                    (event_json, plan_id, slot_id)
                    for slot_id, event_json in pushed_by_slot.items()
                ],
            )
        return len(pushed_by_slot)

    def bulk_update_session_matches(
        self,
        updates: list[dict[str, Any]],
    ) -> int:
        """Update matched activity ids and statuses for multiple sessions.

        Args:
            updates: Items containing ``session_id``, ``matched_activity_id``, and
                ``status`` keys.

        Returns:
            Number of updated session rows.
        """
        if not updates:
            return 0

        with self._session.cursor() as cursor:
            cursor.executemany(
                "UPDATE plan_sessions SET matched_activity_id = ?, status = ? "
                "WHERE id = ?",
                [
                    (
                        item.get("matched_activity_id"),
                        item.get("status", "pending"),
                        item["session_id"],
                    )
                    for item in updates
                ],
            )
        return len(updates)


def _macro_plan_from_row(row: Any) -> MacroPlanRow:
    """Convert a sqlite3.Row to MacroPlanRow."""
    return MacroPlanRow(
        id=row["id"],
        goal_type=row["goal_type"],
        goal_date=row["goal_date"],
        plan_start=row["plan_start"],
        total_weeks=row["total_weeks"],
        ambition_level=row["ambition_level"],
        weeks_json=row["weeks_json"],
        coaching_brief=row["coaching_brief"],
        revision=row["revision"],
        revision_reason=row["revision_reason"],
        status=row["status"],
        created_at=row["created_at"],
        updated_at=row["updated_at"],
    )


def _plan_from_row(row: Any) -> PlanRow:
    """Convert a sqlite3.Row to PlanRow."""
    keys = set(row.keys()) if hasattr(row, "keys") else set()
    return PlanRow(
        id=row["id"],
        name=row["name"],
        goal_type=row["goal_type"],
        goal_date=row["goal_date"],
        plan_start=row["plan_start"],
        athlete_state_json=row["athlete_state_json"],
        solve_result_json=row["solve_result_json"],
        solver_version=row["solver_version"],
        input_hash=row["input_hash"],
        macro_plan_id=row["macro_plan_id"] if "macro_plan_id" in keys else None,
        revision=row["revision"],
        status=row["status"],
        created_at=row["created_at"],
        updated_at=row["updated_at"],
    )


def _session_from_row(row: Any) -> PlanSessionRow:
    """Convert a sqlite3.Row to PlanSessionRow."""
    keys = set(row.keys()) if hasattr(row, "keys") else set()
    return PlanSessionRow(
        id=row["id"],
        plan_id=row["plan_id"],
        slot_id=row["slot_id"],
        date=row["date"],
        week_index=row["week_index"],
        phase_type=row["phase_type"],
        sport=row["sport"],
        activity_key=row["activity_key"],
        family=row["family"],
        target_tss=row["target_tss"],
        achieved_tss=row["achieved_tss"],
        duration_minutes=row["duration_minutes"],
        workout_json=row["workout_json"],
        matched_activity_id=row["matched_activity_id"],
        status=row["status"],
        duration_target_minutes=(
            row["duration_target_minutes"]
            if "duration_target_minutes" in keys
            else None
        ),
        tid_fractions_json=(
            row["tid_fractions_json"] if "tid_fractions_json" in keys else None
        ),
        pushed_event_json=(
            row["pushed_event_json"] if "pushed_event_json" in keys else None
        ),
        optional=bool(row["optional"]) if "optional" in keys else False,
    )
